import { ApiProperty } from '@nestjs/swagger';

import { PaymentMethodStatusEnum } from '@prisma/client';

export class PaymentMethodDto {
	@ApiProperty({
		type: 'string',
	})
	id: string;
	@ApiProperty({
		type: 'string',
	})
	name: string;
	@ApiProperty({
		type: 'string',
	})
	description: string;
	@ApiProperty({
		type: 'string',
		format: 'date-time',
	})
	createAt: Date;
	@ApiProperty({
		type: 'string',
		format: 'date-time',
	})
	updateAt: Date;
	@ApiProperty({
		type: 'string',
		format: 'date-time',
		nullable: true,
	})
	deletedAt: Date | null;
	@ApiProperty({
		enum: PaymentMethodStatusEnum,
		enumName: 'PaymentMethodStatusEnum',
	})
	status: PaymentMethodStatusEnum;
}
