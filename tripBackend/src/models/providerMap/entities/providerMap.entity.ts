import { ApiProperty } from '@nestjs/swagger';

import { MapAddressEntity } from '../../mapAddress/entities/mapAddress.entity';

export class ProviderMapEntity {
	@ApiProperty({
		type: 'string',
	})
	id: string;
	@ApiProperty({
		type: 'string',
	})
	name: string;
	@ApiProperty({
		type: 'string',
	})
	description: string;
	@ApiProperty({
		type: 'string',
		format: 'date-time',
	})
	createAt: Date;
	@ApiProperty({
		type: 'string',
		format: 'date-time',
	})
	updateAt: Date;
	@ApiProperty({
		type: 'string',
		format: 'date-time',
		nullable: true,
	})
	deletedAt: Date | null;
	@ApiProperty({
		type: () => MapAddressEntity,
		isArray: true,
		required: false,
	})
	mapAddress?: MapAddressEntity[];
}
